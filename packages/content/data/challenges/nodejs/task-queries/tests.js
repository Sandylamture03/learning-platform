// The queries run against PGlite, a real PostgreSQL compiled to WebAssembly, set up to answer like the pg package.
import { PGlite, types } from '@electric-sql/pglite';
import { afterAll, beforeAll, beforeEach, describe, expect, it } from 'vitest';
import { completeTask, createTask, listTasks, projectSummary, renameProject } from './solution.js';

let pglite;
/** A pg-like client: { rows, rowCount }, and bigint values as strings, as pg returns them. */
const db = {
  async query(text, values) {
    const result = await pglite.query(text, values);
    return { rows: result.rows, rowCount: result.affectedRows ?? result.rows.length };
  },
};

beforeAll(async () => {
  pglite = new PGlite({ parsers: { [types.INT8]: (value) => value } });
  await pglite.exec(`
    CREATE TABLE projects (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL UNIQUE);
    CREATE TABLE tasks (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      project_id integer NOT NULL REFERENCES projects (id),
      title text NOT NULL,
      done boolean NOT NULL DEFAULT false
    );`);
});
afterAll(() => pglite.close());
beforeEach(async () => {
  await pglite.exec(`
    TRUNCATE tasks, projects RESTART IDENTITY;
    INSERT INTO projects (name) VALUES ('Launch'), ('Admin'), ('Empty');`);
});

describe('task queries', () => {
  it('create a task and return it, with a camelCase projectId', async () => {
    expect(await createTask(db, { projectId: 1, title: 'Write the report' })).toEqual({
      id: 1,
      projectId: 1,
      title: 'Write the report',
      done: false,
    });
  });

  it('store any title as it is, because values go in as parameters', async () => {
    const title = "Robert'); DROP TABLE tasks; --";
    await createTask(db, { projectId: 1, title });
    expect((await listTasks(db, 1)).map((t) => t.title)).toEqual([title]);
  });

  it('list one project’s tasks in order, all or only open or done ones', async () => {
    await createTask(db, { projectId: 1, title: 'Write the report' });
    await createTask(db, { projectId: 2, title: 'Pay the invoice' });
    await createTask(db, { projectId: 1, title: 'Ship it' });
    await completeTask(db, 1);
    expect((await listTasks(db, 1)).map((t) => t.title)).toEqual(['Write the report', 'Ship it']);
    expect((await listTasks(db, 1, { done: false })).map((t) => t.title)).toEqual(['Ship it']);
    expect((await listTasks(db, 1, { done: true })).map((t) => t.title)).toEqual(['Write the report']);
  });

  it('complete a task, and say false for one that does not exist', async () => {
    await createTask(db, { projectId: 1, title: 'Write the report' });
    expect(await completeTask(db, 1)).toBe(true);
    expect(await completeTask(db, 42)).toBe(false);
  });

  it('summarise every project with numbers, including one with no tasks', async () => {
    await createTask(db, { projectId: 1, title: 'Write the report' });
    await createTask(db, { projectId: 1, title: 'Ship it' });
    await createTask(db, { projectId: 2, title: 'Pay the invoice' });
    await completeTask(db, 2);
    expect(await projectSummary(db)).toEqual([
      { name: 'Admin', open: 1, done: 0 },
      { name: 'Empty', open: 0, done: 0 },
      { name: 'Launch', open: 1, done: 1 },
    ]);
  });

  it('rename a project, and report a taken name or a missing project instead of throwing', async () => {
    expect(await renameProject(db, 3, 'Later')).toBe('renamed');
    expect(await renameProject(db, 3, 'Launch')).toBe('taken');
    expect(await renameProject(db, 99, 'Anything')).toBe('missing');
    expect((await projectSummary(db)).map((p) => p.name)).toEqual(['Admin', 'Later', 'Launch']);
  });
});
